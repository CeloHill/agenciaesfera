const initTestimonialsCarousel = () => {
  if (!process.client || !gsap || !ScrollTrigger) return
  if (!testimonialsContainerRef.value || !testimonialsTrackRef.value) {
    setTimeout(() => {
      initTestimonialsCarousel()
    }, 100)
    return
  }
  
  const track = testimonialsTrackRef.value
  const container = testimonialsContainerRef.value
  
  gsap.set(track, {
    x: '50%'
  })
  
  ScrollTrigger.create({
    trigger: testimonialsSectionRef.value,
    start: 'top 70%',
    once: true,
    onEnter: () => {
      gsap.to(track, {
        x: '0%',
        duration: 1.5,
        ease: 'power2.out',
        onComplete: () => {
          testimonialsCurrentX = 0
          updateTestimonialsScrollbar()
        }
      })
    }
  })
  
  let isDragging = false
  let startX = 0
  let scrollLeft = 0
  let dragStartX = 0
  let velocity = 0
  let lastX = 0
  let lastTime = 0
  
  const handleMouseDown = (e) => {
    if (testimonialsInertiaAnimation) {
      testimonialsInertiaAnimation.kill()
      testimonialsInertiaAnimation = null
    }
    
    isDragging = true
    dragStartX = e.pageX
    startX = e.pageX - container.getBoundingClientRect().left
    scrollLeft = testimonialsCurrentX
    lastX = e.pageX
    lastTime = Date.now()
    container.style.cursor = 'grabbing'
    e.preventDefault()
  }
  
  const handleMouseUp = (e) => {
    if (isDragging) {
      const maxScroll = -(track.scrollWidth - container.offsetWidth)
      
      if (Math.abs(velocity) > 0.5) {
        const targetX = testimonialsCurrentX + (velocity * 50)
        const finalX = Math.max(maxScroll, Math.min(0, targetX))
        
        testimonialsInertiaAnimation = gsap.to(track, {
          x: finalX,
          duration: Math.min(Math.abs(velocity) * 0.5, 1),
          ease: 'power2.out',
          onUpdate: () => {
            const transform = gsap.getProperty(track, 'x')
            testimonialsCurrentX = typeof transform === 'string' ? parseFloat(transform) : transform
            updateTestimonialsScrollbar()
          },
          onComplete: () => {
            testimonialsCurrentX = finalX
            updateTestimonialsScrollbar()
            velocity = 0
          }
        })
      } else {
        gsap.to(track, {
          x: testimonialsCurrentX,
          duration: 0.3,
          ease: 'power2.out',
          onComplete: () => {
            updateTestimonialsScrollbar()
          }
        })
      }
    }
    
    isDragging = false
    container.style.cursor = 'grab'
    dragStartX = 0
    velocity = 0
  }
  
  const handleMouseMove = (e) => {
    if (!isDragging) return
    e.preventDefault()
    
    const now = Date.now()
    const deltaTime = now - lastTime
    const deltaX = e.pageX - lastX
    
    if (deltaTime > 0) {
      velocity = deltaX / deltaTime
    }
    
    lastX = e.pageX
    lastTime = now
    
    const x = e.pageX - container.getBoundingClientRect().left
    const walk = (x - startX) * 2
    testimonialsCurrentX = scrollLeft + walk
    
    const maxScroll = -(track.scrollWidth - container.offsetWidth)
    testimonialsCurrentX = Math.max(maxScroll, Math.min(0, testimonialsCurrentX))
    
    gsap.to(track, {
      x: testimonialsCurrentX,
      duration: 0.1,
      ease: 'power1.out'
    })
    
    updateTestimonialsScrollbar()
  }
  
  const handleTouchStart = (e) => {
    if (testimonialsInertiaAnimation) {
      testimonialsInertiaAnimation.kill()
      testimonialsInertiaAnimation = null
    }
    
    isDragging = true
    startX = e.touches[0].pageX - container.getBoundingClientRect().left
    scrollLeft = testimonialsCurrentX
    lastX = e.touches[0].pageX
    lastTime = Date.now()
  }
  
  const handleTouchMove = (e) => {
    if (!isDragging) return
    e.preventDefault()
    
    const now = Date.now()
    const deltaTime = now - lastTime
    const deltaX = e.touches[0].pageX - lastX
    
    if (deltaTime > 0) {
      velocity = deltaX / deltaTime
    }
    
    lastX = e.touches[0].pageX
    lastTime = now
    
    const x = e.touches[0].pageX - container.getBoundingClientRect().left
    const walk = (x - startX) * 2
    testimonialsCurrentX = scrollLeft + walk
    
    const maxScroll = -(track.scrollWidth - container.offsetWidth)
    testimonialsCurrentX = Math.max(maxScroll, Math.min(0, testimonialsCurrentX))
    
    gsap.to(track, {
      x: testimonialsCurrentX,
      duration: 0.1,
      ease: 'power1.out'
    })
    
    updateTestimonialsScrollbar()
  }
  
  const handleTouchEnd = () => {
    if (isDragging) {
      const maxScroll = -(track.scrollWidth - container.offsetWidth)
      
      if (Math.abs(velocity) > 0.5) {
        const targetX = testimonialsCurrentX + (velocity * 50)
        const finalX = Math.max(maxScroll, Math.min(0, targetX))
        
        testimonialsInertiaAnimation = gsap.to(track, {
          x: finalX,
          duration: Math.min(Math.abs(velocity) * 0.5, 1),
          ease: 'power2.out',
          onUpdate: () => {
            const transform = gsap.getProperty(track, 'x')
            testimonialsCurrentX = typeof transform === 'string' ? parseFloat(transform) : transform
            updateTestimonialsScrollbar()
          },
          onComplete: () => {
            testimonialsCurrentX = finalX
            updateTestimonialsScrollbar()
            velocity = 0
          }
        })
      } else {
        gsap.to(track, {
          x: testimonialsCurrentX,
          duration: 0.3,
          ease: 'power2.out',
          onComplete: () => {
            updateTestimonialsScrollbar()
          }
        })
      }
    }
    
    isDragging = false
    velocity = 0
  }
  
  container.addEventListener('mousedown', handleMouseDown)
  document.addEventListener('mouseup', handleMouseUp)
  document.addEventListener('mouseleave', handleMouseUp)
  document.addEventListener('mousemove', handleMouseMove)
  
  container.addEventListener('touchstart', handleTouchStart, { passive: false })
  container.addEventListener('touchmove', handleTouchMove, { passive: false })
  container.addEventListener('touchend', handleTouchEnd)
  
  if (testimonialsResizeHandler) {
    window.removeEventListener('resize', testimonialsResizeHandler)
  }
  
  testimonialsResizeHandler = () => {
    updateTestimonialsScrollbar()
  }
  
  window.addEventListener('resize', testimonialsResizeHandler)
  
  testimonialsDragHandlers = {
    container,
    handleMouseDown,
    handleMouseUp,
    handleMouseMove,
    handleTouchStart,
    handleTouchMove,
    handleTouchEnd
  }
  
  nextTick(() => {
    updateTestimonialsScrollbar()
  })
}

